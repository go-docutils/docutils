// isCombining reports whether r has a nonzero canonical combining
// class, and so adds no column of its own.
func isCombining(r rune) bool {
	i := sort.Search(len(combiningRanges), func(i int) bool {
		return combiningRanges[i][1] >= r
	})
	return i < len(combiningRanges) && r >= combiningRanges[i][0]
}

// ColumnWidth is docutils' utils.column_width: how many columns s
// occupies, counting an East Asian Wide or Fullwidth character as two
// and a combining character as none.
//
// It is NOT TableColumnWidth, and the difference is deliberate on
// docutils' side: a table's geometry comes from pad_double_width, which
// doubles wide characters and says nothing about combining ones, while
// column_width subtracts them. The two are a column count for different
// purposes and this package now has both, each named for its own.
func ColumnWidth(s string) int {
	// docutils' arithmetic exactly: SUM the East Asian widths, then
	// SUBTRACT one per combining character. Those are two independent
	// steps, not a three-way choice -- U+3099 (COMBINING
	// KATAKANA-HIRAGANA VOICED SOUND MARK) is Wide AND combining, so it
	// is 2-1 = 1, where treating "combining" as "no column at all"
	// makes it 0. One character in a 1245-character sample against the
	// reference, and the only one this got wrong.
	n := 0
	for _, r := range s {
		if isEastAsianWide(r) {
			n += 2
		} else {
			n++
		}
		if isCombining(r) {
			n--
		}
	}
	return n
}
