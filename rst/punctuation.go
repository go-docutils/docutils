// EARLIER version of this file ran them through the same regex-range
// expansion delimiters needs, which reorders by code point and silently
// broke every same-index pairing that wasn't already in code-point order
// (caught by cross-checking quotedStart against Python's own match_chars
// for a battery of real quote pairs, not by inspection -- the character
// SETS matched the reference perfectly even with the wrong order, since
// membership doesn't care about position). delimiters/closing_delimiters
// ARE regex-range syntax in the source (e.g. "a-z"), so those two ARE the
