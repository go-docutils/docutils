// This file ports docutils.utils.punctuation_chars' character classes and
// docutils.parsers.rst.states.Inliner's start_string_prefix/end_string_suffix
// boundary rules verbatim -- not "any punctuation" (this parser's own
// earlier, simpler approximation via unicode.IsPunct, which treated an
// opening and a closing bracket/quote identically). Real docutils
// distinguishes them: a markup start-string may be preceded by an OPENER or
// a DELIMITER but never a CLOSER or a CLOSING-DELIMITER, and a markup
// end-string may be followed by a CLOSER, a DELIMITER, or a
// CLOSING-DELIMITER but never an OPENER -- which is exactly why real
// docutils accepts "(*emphasis*)" and "*emphasis*." but rejects
// ")*emphasis*(" and "*emphasis*)" as genuine markup at all (see the
