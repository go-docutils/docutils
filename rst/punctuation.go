const punctClosingDelimiters = "!,.;?\\"

// punctQuotePairs mirrors docutils.utils.punctuation_chars.quote_pairs: an
// opener that additionally matches one or more closers BESIDES its own
// same-index closer (mixed quotation-mark conventions across languages --
// French, German, Polish, Hungarian, Greek, ... -- where the SAME character
// opens a quotation in one convention and closes it in another).
var punctQuotePairs = map[rune]string{
	'\u00bb': "\u00bb",
	'\u2018': "\u201a",
	'\u2019': "\u2019",
	'\u201a': "\u2018\u2019",
	'\u201c': "\u201e",
	'\u201e': "\u201c\u201d",
	'\u201d': "\u201d",
	'\u203a': "\u203a",
}

func isOpener(r rune) bool           { return strings.ContainsRune(punctOpeners, r) }
func isCloser(r rune) bool           { return strings.ContainsRune(punctClosers, r) }
func isDelimiterChar(r rune) bool    { return strings.ContainsRune(punctDelimiters, r) }
func isClosingDelimiter(r rune) bool { return strings.ContainsRune(punctClosingDelimiters, r) }

// quotedStart mirrors punctuation_chars.match_chars(prestart, poststart),
// called from real docutils' Inliner.quoted_start: true when prestart is a
// registered opener whose matching closer (same position in the ordered
// openers/closers strings) IS poststart, or poststart is one of prestart's
// extra quote_pairs partners. A markup start-string immediately sandwiched
// between such a pair (e.g. "(*)text", opener "(" then closer ")" with
// nothing else between) is rejected as a genuine start even though the
// basic boundary rule alone would accept it.
//
// Deliberately uses the FIRST occurrence of prestart in openers (Python's
// str.index, which match_chars calls, does the same), not every occurrence
// — real docutils' own openers string repeats exactly one character (U+301D
// "〝", at two positions pairing with two different closers, U+301E and
// U+301F); only the first pairing is ever reachable through match_chars,
// the second is a real, if obscure, quirk of the reference implementation
// this mirrors rather than improves on.
func quotedStart(prestart, poststart rune) bool {
	byteIdx := strings.IndexRune(punctOpeners, prestart)
	if byteIdx < 0 {
		// Python's own match_chars returns False here directly (a bare
		// `except ValueError: return False`) without even consulting
		// quote_pairs — every quote_pairs key does also appear in openers,
		// so this branch is unreachable for any real quote_pairs lookup,
		// but matching the exact control flow rather than an
		// only-coincidentally-equivalent shortcut is the safer choice.
		return false
	}
	runeIdx := len([]rune(punctOpeners[:byteIdx]))
	closersRunes := []rune(punctClosers)
	if runeIdx < len(closersRunes) && poststart == closersRunes[runeIdx] {
		return true
	}
	if extra, ok := punctQuotePairs[prestart]; ok && strings.ContainsRune(extra, poststart) {
		return true
	}
	return false
}
